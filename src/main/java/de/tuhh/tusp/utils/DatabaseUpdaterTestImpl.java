package de.tuhh.tusp.utils;

import java.io.IOException;
import java.io.InputStream;
import java.util.HashMap;
import java.util.Map;
import java.util.SortedSet;
import java.util.TreeMap;
import java.util.TreeSet;

import org.apache.commons.io.IOUtils;
import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;
import org.jooq.DSLContext;
import org.jooq.Query;
import org.jooq.SQLDialect;
import org.jooq.conf.Settings;
import org.jooq.impl.DSL;
import org.jooq.impl.TableImpl;
import org.reflections.Reflections;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.transaction.annotation.Transactional;

public class DatabaseUpdaterTestImpl implements DatabaseUpdater {

	private static final String DB_FILE_UI_TEST = "Database_ui_test.sql";
	private static Logger logger = LogManager.getLogger(DatabaseUpdaterTestImpl.class);

	/**
	 * Bereinigt PostgreSQL-Eigenheiten aus einem SQL
	 *
	 * @param sql
	 * @return SQL ohne Dialekt
	 */
	private static String sanitizeSql(String sql) {

		// Autoincrement wird anders umgesetzt
		sql = sql.replaceFirst("not null default nextval\\(.*\\)", "auto_increment not null");

		// Typen-Convertieung macht H2 implizit
		sql = sql.replaceAll("'::timestamp", "'");
		sql = sql.replaceAll("'::regclass", "'");

		// H2 kennt keine time zone
		sql = sql.replaceAll("without time zone", "");

		if (sql.contains("generated by default as identity")) {
			sql = sql.replaceAll(",\\s+constraint \"[a-z0-9_]+\"\\s+primary key \\(\"id\"\\)", "");
		}

		sql = sql.replace("\"session_id\" bigint not null generated by default as identity,",
				"\"session_id\" bigint not null,");

		return sql;
	}

	@SuppressWarnings("rawtypes")
	private HashMap<String, TableImpl> createTableStatements = null;

	@Value("${url}")
	private String url;

	@Value("${username}")
	private String username;

	@Value("${password}")
	private String password;

	@Value("${dialect}")
	private String dialect;

	@Override
	@Transactional
	@SuppressWarnings({ "rawtypes" })
	public void buildTestTables(DSLContext ctx) throws Exception {

		logger.info("Baue H2 Tabellen neu auf...");

		// Schema erzeugen, wenn es fehlt
		ctx.dropSchemaIfExists("public").execute();
		ctx.createSchema("public").execute();

		if (createTableStatements == null) {
			// Queue erzeugen mit allen von JOOQ generierten Klassen
			createTableStatements = new HashMap<>();
			Reflections reflections = new Reflections("org.jooq.generated");
			for (Class<? extends TableImpl> c : reflections.getSubTypesOf(TableImpl.class)) {
				TableImpl instance = c.newInstance();
				for (Query query : DSL.using(SQLDialect.H2, new Settings().withRenderFormatted(true)).ddl(instance)
						.queries()) {
					createTableStatements.put(query.toString(), instance);
				}
			}

		}

		// Sortieren
		SortedSet<String> keys = new TreeSet<>(createTableStatements.keySet());
		Map<String, TableImpl> queue = new TreeMap<>();
		for (String key : keys) {
			queue.put(key, createTableStatements.get(key));
		}

		// Queue abarbeiten
		int lastRunSize = Integer.MAX_VALUE;
		while (lastRunSize > queue.size()) {
			lastRunSize = queue.size();

			for (Object query : queue.keySet().toArray()) {
				TableImpl object = queue.get(query);
				try {

					logger.debug("Baue H2 Tabelle für: " + object.getClass());

					ctx.dropTableIfExists(object).execute();

					// JOOQ kann die Syntax von Postgres nicht richtig für H2
					// umwandeln. Daher nacharbeiten:
					String sql = sanitizeSql((String) query) + ";";

					if (sql.startsWith("create index") || sql.startsWith("create unique index")
							|| sql.startsWith("create schema")) {
						logger.warn(sql + "\n");
					} else {
						logger.trace(sql + "\n");
						ctx.execute(sql);
					}

					queue.remove(query);
				} catch (org.jooq.exception.DataAccessException e) {
					logger.warn(
							"Bauen von H2 Tabelle fehlgeschlagen für: " + object.getClass() + "\n" + e.getMessage());
					// Shit happens, dann fehlte wohl ne abhängigkeit
				}
			}
		}

		if (!queue.isEmpty()) {
			throw new Exception("Es konnten nicht alle JOOQ-Tabellen in der Test-DB erstellt werden!");
		}
	}

	@Override
	@Transactional
	public void initDb(DSLContext context) throws Exception {

		logger.debug("Starte DB-Versions-Check");

		if (!"h2".equals(dialect)) {
			throw new RuntimeException("Der SQL-Dialekt '" + dialect + "' wird nicht unterstützt!");
		}

		// H2 Datenbank erzeugen
		buildTestTables(context);
		String sqls = readClasspathFile(DB_FILE_UI_TEST);
		for (String sql : sqls.split(";\r?\n")) {
			context.execute(sql);
		}

	}

	/**
	 * Liest eine Datei aus dem ClassPath
	 *
	 * @param path
	 * @return den Dateiinhalt
	 * @throws IOException bei IO Problemen
	 */
	private String readClasspathFile(String path) throws IOException {

		InputStream in = getClass().getClassLoader().getResourceAsStream(path);

		return IOUtils.toString(in, "UTF-8");
	}

}
